"""Start and stop one guarded scratch node from a candidate tree.

The node runs the candidate's own ``python -m topos.cli`` with every ``~/.topos``
default pinned inside a scratch HOME (the same overrides Rig D's node plan sets),
background work off, no control plane and no model host. Three guards, each
independent of the others:

* a generated ``sitecustomize`` arms ``tests/live_db_watch`` against the REAL
  home before HOME moves, so any read-write open of the owner's database, ``.env``
  or socket is refused and journalled (the journal fails the gate whatever the
  node's exit code says; see ``scripts/live_db_tripwire.py`` for why);
* an audit hook in the same file refuses every outbound connect except the
  scratch sockets and two loopback ports (the node's own and a dead control-plane
  port), and refuses launching ``open``/``ollama`` (a closed LOCAL model URL makes
  the engine run ``open -a Ollama``; the dead model URL here is non-local);
* :func:`wait_serving` reads the node's first ``Serving database`` line and kills
  the process if it names anything but the scratch file. ``--db-path`` is not
  used: it is ignored when settings import first, and the node then serves the
  slot under HOME. HOME is scratch, so the slot is scratch too.
"""
