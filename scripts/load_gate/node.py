def write_guard_site(directory: Path) -> Path:
    """The generated ``sitecustomize`` in ``directory``; put that directory first on the node's PYTHONPATH."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "sitecustomize.py").write_text(_SITECUSTOMIZE, encoding="utf-8")
    return directory


def real_home() -> Path:
    """The owner's home from the password database, not from HOME (which a caller may have moved)."""
    import pwd

    return Path(pwd.getpwuid(os.getuid()).pw_dir)


def live_db_user_version(home: Optional[Path] = None) -> Optional[int]:
    """``PRAGMA user_version`` of the owner's database, read-only; None when there is no such file."""
    db = (home or real_home()) / ".topos" / "database.db"
    if not db.exists():
        return None
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    try:
        return int(conn.execute("PRAGMA user_version").fetchone()[0])
    finally:
        conn.close()


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


class ScratchNode:
    """One node process: ``home/.topos`` holds its database, key, socket and logs."""

    def __init__(self, *, root: Path, node_tree: Path, node_python: Path, label: str):
        self.root = root.resolve()
        self.node_tree = node_tree.resolve()
        self.node_python = node_python
        self.label = label
        self.home = self.root / "h"
        self.topos_dir = self.home / ".topos"
        self.db_path = self.topos_dir / "database.db"
        self.socket_path = self.topos_dir / "engine.sock"
        self.log_path = self.root / f"{label}.log"
        self.journal_path = self.root / "live-db-journal.txt"
        self.egress_path = self.root / "egress-blocked.txt"
        self.guard_dir = self.root / "guard"
        self.port = free_port()
        self.process: Optional[subprocess.Popen] = None
        self.serving: Optional[dict] = None
        #: Set last, over everything above; the seed's one boot uses it (see seed.build).
        self.extra_env: dict = {}
        if len(str(self.socket_path)) > 100:
            raise ValueError(f"socket path too long for macOS ({len(str(self.socket_path))} chars): {self.socket_path}")

    def env(self) -> dict:
        for d in (self.topos_dir, self.root / "tmp"):
            d.mkdir(parents=True, exist_ok=True)
        write_guard_site(self.guard_dir)
        env_file = self.topos_dir / ".env"
        env_file.write_text("TOPOS_KEY=load-gate-synthetic-only\n", encoding="utf-8")
        env_file.chmod(0o600)
        owner = real_home()
        env = {
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(self.home),
            "TMPDIR": str(self.root / "tmp"), "LANG": "en_US.UTF-8", "LC_ALL": "en_US.UTF-8",
            "PYTHONPATH": os.pathsep.join([str(self.guard_dir), str(self.node_tree)]),
            "PYTHONDONTWRITEBYTECODE": "1", "PYTHONUNBUFFERED": "1",
            # The shared, read-only in-process model caches; nothing is downloaded.
            "HF_HOME": str(owner / ".cache" / "huggingface"), "TORCH_HOME": str(owner / ".cache" / "torch"),
            "HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1", "HF_HUB_DISABLE_TELEMETRY": "1", "DO_NOT_TRACK": "1",
            "TOPOS_KEY": "load-gate-synthetic-only",
            "TOPOS_ENV_FILE": str(env_file), "TOPOS_UDS_PATH": str(self.socket_path),
            "TOPOS_DATABASE_PATH": str(self.db_path), "TOPOS_BACKUP_DIR": str(self.topos_dir / "backups"),
            "TOPOS_INGESTION_BASE_PATH": str(self.topos_dir / "ingestion"),
            "TOPOS_SCOPE_SHADOW_LOG": str(self.topos_dir / "scope_shadow.jsonl"),
            "TOPOS_CONTROL_PLANE_URL": f"ws://127.0.0.1:{DEAD_CP_PORT}/ws/engine",
            "TOPOS_SYNC_URL": f"ws://127.0.0.1:{DEAD_CP_PORT}/ws/sync", "ENABLE_SYNC": "false",
            "TOPOS_HOST": "127.0.0.1", "ENGINE_NAME": f"load gate {self.label}",
            "TOPOS_MIN_FREE_DISK_BYTES": NODE_MIN_FREE_DISK_BYTES,
            # The write gate's watchdog: a transaction left open outside the gate is logged after 5 s.
            "TOPOS_DB_TXN_WATCHDOG": "1",
            # The node force-exits this long after a stop it could not finish (default 60 s).
            "TOPOS_SHUTDOWN_EXIT_DEADLINE_SECONDS": "20",
            # Guards (sitecustomize above).
            "TOPOS_LOAD_GATE_ROOT": str(self.root), "TOPOS_LOAD_GATE_REAL_HOME": str(owner),
            "TOPOS_LOAD_GATE_LOOPBACK_PORTS": f"{self.port},{DEAD_CP_PORT}",
            "TOPOS_LOAD_GATE_EGRESS_LOG": str(self.egress_path),
            "TOPOS_LIVE_DB_WATCH_MODULE": str(WATCH_MODULE_PATH), "TOPOS_LIVE_DB_JOURNAL": str(self.journal_path),
        }
        env.update(QUIET_NODE_ENV)
        env.update(self.extra_env)
        for name in ("OPENAI_API_KEY", "RED_PILL_API_KEY", "GT_CLOUD_API_KEY", "TOPOS_OWNER_KEY"):
            env.pop(name, None)
        return env

    def verify_python(self) -> dict:
        """The interpreter is 3.12 and imports ``topos`` from the candidate tree, under the armed guards."""
        probe = ("import json, sys, topos, sqlite3; m = sys.modules.get('topos_live_db_watch');"
                 "print(json.dumps({'python': sys.version.split()[0], 'topos': topos.__file__,"
                 "'guard': bool(m and m.file_guard_is_installed())}))")
        out = subprocess.run([str(self.node_python), "-c", probe], env=self.env(), cwd=self.root,
                             capture_output=True, text=True, timeout=120)
        if out.returncode != 0:
            raise RuntimeError(f"node interpreter probe failed: {out.stderr.strip()[-400:]}")
        info = json.loads(out.stdout.strip().splitlines()[-1])
        if not info["python"].startswith("3.12."):
            raise RuntimeError(f"the node must run on Python 3.12, not {info['python']}")
        if not Path(info["topos"]).resolve().is_relative_to(self.node_tree):
            raise RuntimeError(f"topos imports from {info['topos']}, not the candidate tree {self.node_tree}")
        if not info["guard"]:
            raise RuntimeError("the owner-database guard did not arm in the node interpreter")
        return info

    def start(self) -> None:
        argv = [str(self.node_python), "-m", "topos.cli", "--host", "127.0.0.1", "--port", str(self.port),
                "--no-tray", "--skip-update-check"]
        env = self.env()  # makes the run's folders, so it comes before the log opens
        log = self.log_path.open("ab")
        self.process = subprocess.Popen(argv, env=env, cwd=self.root, stdout=log, stderr=subprocess.STDOUT,
                                        stdin=subprocess.DEVNULL, start_new_session=True)
        log.close()

    def wait_serving(self, timeout_s: float = 120.0) -> dict:
        """The node's own ``Serving database`` line. Kills the node unless it names the scratch file."""
        deadline = time.monotonic() + timeout_s
        while time.monotonic() < deadline:
            if self.process and self.process.poll() is not None:
                raise RuntimeError(f"node exited {self.process.returncode} before naming its database; "
                                   f"see {self.log_path}")
            text = self.log_path.read_text(encoding="utf-8", errors="replace") if self.log_path.exists() else ""
            match = SERVING.search(text)
            if match:
                path = Path(match.group("path")).resolve()
                if path != self.db_path.resolve():
                    self.kill()
                    raise RuntimeError(f"node served {path}, not the scratch database; killed it")
                self.serving = {"path": str(path), "source": match.group("source")}
                return self.serving
            time.sleep(0.25)
        self.kill()
        raise RuntimeError(f"node never named its database within {timeout_s:.0f} s; killed it")

    def wait_healthy(self, timeout_s: float = 300.0) -> float:
        import httpx

        started = time.monotonic()
        deadline = started + timeout_s
        with httpx.Client(base_url=f"http://127.0.0.1:{self.port}", timeout=10) as client:
            while time.monotonic() < deadline:
                if self.process and self.process.poll() is not None:
                    raise RuntimeError(f"node exited {self.process.returncode} during start-up; see {self.log_path}")
                try:
                    r = client.get("/healthcheck")
                    body = r.json() if r.status_code == 200 else {}
                except (httpx.HTTPError, ValueError):
                    body = {}
                served = body.get("database_path")
                if served and Path(served).resolve() != self.db_path.resolve():
                    self.kill()
                    raise RuntimeError(f"healthcheck names {served}, not the scratch database; killed the node")
                if body.get("db_ok") is True and self.socket_path.exists():
                    return time.monotonic() - started
                time.sleep(0.5)
        raise RuntimeError(f"node not healthy within {timeout_s:.0f} s; see {self.log_path}")

    def stop(self, timeout_s: float = 30.0) -> Optional[int]:
        """SIGINT (uvicorn's graceful stop, so the guard's atexit journal runs), then TERM, then KILL."""
        if self.process is None or self.process.poll() is not None:
            return self.process.returncode if self.process else None
        for sig, wait in ((signal.SIGINT, timeout_s), (signal.SIGTERM, 15.0)):
            try:
                os.killpg(self.process.pid, sig)
            except ProcessLookupError:
                break
            try:
                return self.process.wait(timeout=wait)
            except subprocess.TimeoutExpired:
                continue
        self.kill()
        return self.process.returncode

    def dump_stacks(self) -> str:
        """Every Python thread's stack from the node (SIGUSR1, see the generated sitecustomize), for a hung run."""
        if self.process is None or self.process.poll() is not None:
            return ""
        os.kill(self.process.pid, signal.SIGUSR1)
        time.sleep(2.0)
        path = self.root / f"stacks-{self.process.pid}.txt"
        return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""

    def kill(self) -> None:
        if self.process is None or self.process.poll() is not None:
            return
        try:
            os.killpg(self.process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        self.process.wait(timeout=30)

    def journal_lines(self) -> list[str]:
        if not self.journal_path.exists():
            return []
        return [line for line in self.journal_path.read_text(encoding="utf-8", errors="replace").splitlines() if line]

    def egress_lines(self) -> list[str]:
        if not self.egress_path.exists():
            return []
        return [line for line in self.egress_path.read_text(encoding="utf-8", errors="replace").splitlines() if line]


def other_heavy_runs(patterns=("run_any_to_any_release.py", "scripts.a2a_rig.run", "stress_30.py",
                               "node_load_gate.py")) -> list[str]:
    """Rig D, a stress run or another load gate on this Mac (one heavy run at a time). Commands only, no args."""
    out = subprocess.run(["ps", "-Ao", "pid=,ppid=,command="], capture_output=True, text=True).stdout
    rows = {}
    for line in out.splitlines():
        parts = line.split(None, 2)
        if len(parts) == 3 and parts[0].isdigit() and parts[1].isdigit():
            rows[int(parts[0])] = (int(parts[1]), parts[2])
    # This run's own ancestors (the shell or `uv run` that started it) name this script too.
    mine, pid = set(), os.getpid()
    while pid and pid not in mine:
        mine.add(pid)
        pid = rows.get(pid, (0, ""))[0]
    hits = []
    for pid, (_, command) in rows.items():
        if pid not in mine and any(p in command for p in patterns):
            hits.append(f"{pid} {next(p for p in patterns if p in command)}")
    return hits


